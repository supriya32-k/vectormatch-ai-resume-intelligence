import { AnalysisResult } from '../types';

/**
 * Formats the raw analysis results into a clean, professional, and highly readable Markdown report.
 */
export const generateMarkdownReport = (fileName: string, result: AnalysisResult): string => {
  const cleanFileName = fileName || 'Candidate_Resume';
  const matchPercentage = result.matchPercentage;
  const jobTitle = result.jobTitleMatch || 'Specified Role';
  
  return `# VectorMatch AI - Intelligence Report
**Generated on:** ${new Date().toLocaleString()}
**Candidate Source File:** ${cleanFileName}
**Target Job Match:** ${jobTitle}

================================================================================

## 📊 MATCH ASSESSMENT OVERVIEW
* **Overall Fit Score:** ${matchPercentage}% Match
* **Experience Level Alignment:** ${result.experienceMatch || 'Not Specified'}
* **Immediate Improvement Tasks:** ${result.actionableRecommendations?.length || 0} Action Items

---

## 📝 EXECUTIVE SUMMARY
${result.overallSummary || 'No summary available.'}

---

## 🔍 SEMANTIC SKILLS AUDIT

### ✅ Matching Skills Found
${result.topSkillsFound && result.topSkillsFound.length > 0 
  ? result.topSkillsFound.map(skill => `- [x] ${skill}`).join('\n') 
  : '* No major matching skills explicitly found in the target job description.'}

### ⚠️ Critical Gaps (Missing Skills)
${result.missingCriticalSkills && result.missingCriticalSkills.length > 0 
  ? result.missingCriticalSkills.map(skill => `- [ ] ${skill}`).join('\n') 
  : '* Excellent alignment! No major critical skill gaps identified.'}

---

## 🚀 STRATEGIC IMPROVEMENT PLAN

### Actionable Recommendations
${result.actionableRecommendations && result.actionableRecommendations.length > 0 
  ? result.actionableRecommendations.map((rec, i) => `${i + 1}. ${rec}`).join('\n') 
  : '* No recommendations required.'}

### Optimized Bullet Point Suggestions (Ready for Resume Update)
${result.suggestedBulletPoints && result.suggestedBulletPoints.length > 0 
  ? result.suggestedBulletPoints.map((bullet, i) => `#### Suggestion ${i + 1}:\n> "${bullet}"`).join('\n\n') 
  : '* No specific bullet point rewrites suggested.'}

---

## 🎯 INTERVIEW PREPARATION GUIDE

### Technical Questions & Target Answers
${result.interviewPrep?.technicalQuestions && result.interviewPrep.technicalQuestions.length > 0 
  ? result.interviewPrep.technicalQuestions.map((q, i) => `#### Q${i + 1}: ${q.question}\n**Target Answer Key:**\n${q.targetAnswer}\n`).join('\n') 
  : '* No technical questions generated.'}

### Behavioral Strategy
${result.interviewPrep?.behavioralQuestions && result.interviewPrep.behavioralQuestions.length > 0 
  ? result.interviewPrep.behavioralQuestions.map((q, i) => `#### Q${i + 1}: ${q.question}\n**Recommended Strategy:**\n${q.strategy}\n`).join('\n') 
  : '* No behavioral questions generated.'}

================================================================================
*Confidentiality Notice: This document contains proprietary analysis generated by VectorMatch AI.*
`;
};

/**
 * Initiates a browser-triggered download of the generated content.
 */
export const downloadFile = (content: string, filename: string, contentType: string) => {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
};

/**
 * Handles exporting the analysis result into the selected format.
 */
export const exportAnalysis = (fileName: string, result: AnalysisResult, format: 'md' | 'json') => {
  const baseName = fileName ? fileName.replace(/\.[^/.]+$/, "") : "VectorMatch_Audit";
  if (format === 'md') {
    const markdown = generateMarkdownReport(fileName, result);
    downloadFile(markdown, `${baseName}_AI_Report.md`, 'text/markdown;charset=utf-8;');
  } else if (format === 'json') {
    const jsonContent = JSON.stringify(result, null, 2);
    downloadFile(jsonContent, `${baseName}_AI_Report.json`, 'application/json;charset=utf-8;');
  }
};
